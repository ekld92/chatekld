"""Assemble the model's per-section output into one valid LaTeX **article**.

The prose counterpart of :mod:`deckgen.assemble`: it reuses the whole
document-class-agnostic substrate in :mod:`deckgen.latex` (metadata escaping,
title substitution, dangerous-macro / citation / graphics scanning, comment
stripping, template assembly, and :func:`~deckgen.latex.validate_common`) and
supplies only the article-specific pieces — a prose ``\\documentclass{article}``
preamble, a ``sanitize_article_section`` that accepts prose sections (no frame
gate), and section-presence structural checks — bound into the ``ARTICLE``
:class:`~deckgen.latex.DocClassStrategy`.

Emit-only by design, exactly like deckgen: no compiler is invoked here.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

from deckgen.latex import (
    DocClassStrategy,
    SectionOutput,
    _DOCUMENT_ENV_RE,
    _FENCE_RE,
    _PREAMBLE_LINE_RE,
    _SECTION_RE,
    _sections_block,
    _strip_latex_comments,
    latex_escape_metadata,
    validate_common,
)
# Re-exported so callers can import the substrate from one place (docgen.article),
# mirroring how deckgen.assemble re-exports it.
from deckgen.latex import (  # noqa: F401
    assemble_with_template,
    comment_out_missing_graphics,
    extract_cite_keys,
    extract_graphics_keys,
    find_dangerous_macros,
    substitute_title,
)

# Sentinel tokens for the fallback preamble (used only when there is no user
# template). We avoid str.format / string.Template because the LaTeX body is full
# of ``{``/``}``/``$`` that would collide with those mini-languages.
_ARTICLE_PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{graphicx}
\usepackage{hyperref}
\graphicspath{{figures/}}

\title{@@TITLE@@}
\author{@@AUTHOR@@}
\date{@@DATE@@}

% Generated by docgen — grounded in the user's Obsidian vault (ChatEKLD).
% This file is emitted, not compiled. Compile it yourself, e.g.:  latexmk -pdf <file>.tex

\begin{document}

\maketitle

\tableofcontents

@@SECTIONS@@

\end{document}
"""

# A standalone ``\tableofcontents`` line the model may duplicate (we own the ToC
# in the scaffold). ``\maketitle`` / ``\documentclass`` / ``\title`` are already
# caught by _PREAMBLE_LINE_RE.
_TOC_LINE_RE = re.compile(r"^\s*\\tableofcontents\b")


@dataclass
class DocMeta:
    """CLI-/route-supplied article metadata (no theme/institute, unlike a deck)."""
    title: str
    author: str = ""
    date: str = ""  # empty -> \today


def sanitize_article_section(text: str) -> str:
    """Reduce a model answer to just the article section body we will embed.

    Strips markdown code fences, drops any preamble / document-scaffold lines the
    model emitted despite instructions (including a duplicated ``\\maketitle`` /
    ``\\tableofcontents``), and trims leading prose by slicing from the first
    ``\\section``. Idempotent.

    The article gate is a surviving ``\\section`` (parallel to Beamer's frame
    gate): if none remains the model returned loose prose or a server fallback
    message rather than a real section, so we signal "empty" and the caller
    substitutes a placeholder section instead of leaking text into the body.
    """
    if not text:
        return ""

    kept: list[str] = []
    for line in text.splitlines():
        if _FENCE_RE.match(line):
            continue
        if _PREAMBLE_LINE_RE.match(line):
            continue
        if _DOCUMENT_ENV_RE.match(line):
            continue
        if _TOC_LINE_RE.match(line):
            continue
        kept.append(line)

    body = "\n".join(kept)

    # Trim leading prose to the first \section anchor when present.
    m = _SECTION_RE.search(body)
    if m:
        body = body[m.start():]

    body = body.strip()
    if not _SECTION_RE.search(body):
        return ""
    return body


def assemble_article(sections: list[SectionOutput], meta: DocMeta) -> str:
    """Wrap sanitized article section bodies in the fallback article preamble."""
    sections_block = _sections_block(sections)

    date = meta.date.strip()
    date_value = latex_escape_metadata(date) if date else r"\today"

    out = _ARTICLE_PREAMBLE
    out = out.replace("@@TITLE@@", latex_escape_metadata(meta.title))
    out = out.replace("@@AUTHOR@@", latex_escape_metadata(meta.author))
    out = out.replace("@@DATE@@", date_value)
    out = out.replace("@@SECTIONS@@", sections_block)
    return out


def _article_structural_checks(scan_tex: str) -> list[str]:
    """Article-specific structural warnings over comment-stripped *scan_tex*.

    An article has no frames; the only class-specific structural requirement is
    at least one ``\\section`` (else the body and the table of contents are
    empty). The class-agnostic checks (document env, dangerous macros, citations,
    graphics) are :func:`~deckgen.latex.validate_common`.
    """
    warnings: list[str] = []
    if not _SECTION_RE.search(scan_tex):
        warnings.append("No \\section found — the article has no body content.")
    return warnings


# The article document-class strategy — the docgen twin of deckgen's BEAMER.
ARTICLE = DocClassStrategy(
    name="article",
    preamble_template=_ARTICLE_PREAMBLE,
    structural_checks=_article_structural_checks,
)


def validate_article(
    tex: str,
    *,
    generated_tex: Optional[str] = None,
    known_bib_keys: Optional[set] = None,
    copied_figures: Optional[set] = None,
) -> list[str]:
    """Best-effort structural checks for a LaTeX article. Returns warnings.

    No compiler is invoked (emit-only). Combines the article structural check
    (at least one section) with the shared :func:`~deckgen.latex.validate_common`
    (single document env, unsafe compile-time macros, invented citation keys,
    unresolved graphics). *generated_tex*, when supplied, scopes the danger/cite
    checks to the model-generated span so a trusted template preamble is not
    flagged.
    """
    warnings = list(ARTICLE.structural_checks(_strip_latex_comments(tex)))
    warnings += validate_common(
        tex,
        generated_tex=generated_tex,
        known_bib_keys=known_bib_keys,
        copied_figures=copied_figures,
    )
    return warnings
